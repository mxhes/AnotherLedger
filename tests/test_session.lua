h.test("Session stop/start", function()
  local s = S.new(100)
  S.add(s, 5, L, 3, 110)
  S.stop(s, 200)
  h.eq(s.running, false)
  h.eq(S.elapsed(s, 500), 100)
  h.eq(S.add(s, 5, L, 1, 300), false)
  h.eq(s.items[5].qty, 3)
