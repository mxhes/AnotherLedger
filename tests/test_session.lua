  h.eq(S.zoneSnapshot(s, 1010).Z.subs.B.time, 90)
  h.eq(s.zones.Z.subs.B.time, 80) -- the snapshot did not change the session
  h.eq(S.zoneSnapshot({}, 5), {})
end)

