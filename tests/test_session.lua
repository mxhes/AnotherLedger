h.test("Session place time only grows while the clock runs", function()
  local s = S.new(0)
  S.enterPlace(s, "Z", "A", 0)
  S.stop(s, 50)
  S.start(s, 500)
  S.enterPlace(s, "Z", "B", 520)
  h.eq(s.zones.Z.subs.A.time, 70)
  S.suspend(s, 600)
