h.test("Session suspend/resume", function()
  local s = S.new(0)
  S.suspend(s, 100)
  S.resume(s, 10000)
  h.eq(S.elapsed(s, 10060), 160)
  local t = S.new(0)
  S.stop(t, 100)
  S.suspend(t, 200)
  S.resume(t, 10000)
  h.eq(t.running, false)
  h.eq(S.elapsed(t, 20000), 100)
