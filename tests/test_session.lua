local h = ...
local ns = h.load({ "Util.lua", "Session.lua" })
local S = ns.Session
local L = "|cff0070dd|Hitem:5::::::::|h[Thing]|h|r"

local function count(t) local n = 0 for _ in pairs(t) do n = n + 1 end return n end

h.test("Session.new and elapsed", function()
  local s = S.new(100)
  h.eq(s.running, true)
  h.eq(s.startedAt, 100)
  h.eq(S.elapsed(s, 100), 0)
  h.eq(S.elapsed(s, 160), 60)
end)

h.test("Session.add accumulates and updates lastSeen", function()
  local s = S.new(100)
  h.eq(S.add(s, 5, L, 3, 110), true)
  h.eq(S.add(s, 5, L, 2, 120), true)
  h.eq(s.items[5].qty, 5)
  h.eq(s.items[5].lastSeen, 120)
  h.eq(s.items[5].id, 5)
  h.eq(s.items[5].link, L)
end)

h.test("Session.add keeps variants apart under their key", function()
  local s = S.new(0)
  local ok, item = S.add(s, 50, "a", 1, 5, "50:1477")
  h.eq(ok, true)
  h.eq(item.key, "50:1477")
  S.add(s, 50, "b", 2, 6)
  h.eq(s.items["50:1477"].qty, 1)
  h.eq(s.items[50].qty, 2)
  h.eq(S.hasItemID(s.items, 50), true)
  h.eq(S.hasItemID(s.items, 51), false)
end)

h.test("Session currencies, places and loot-time prices", function()
  local s = S.new(0)
  h.eq(S.addCurrency(s, 3008, "link", 5, 1), true)
  S.addCurrency(s, 3008, nil, 2, 2)
  h.eq(s.currencies[3008].qty, 7)
  h.eq(S.addCurrency(s, 3008, nil, 0, 2), false)
  S.notePlace(s, "Dornogal")
  S.notePlace(s, "The Stonevault (Heroic)")
  S.notePlace(s, "The Stonevault (Heroic)")
  h.eq(S.placeList(s.places), { "The Stonevault (Heroic)", "Dornogal" })
  local _, item = S.add(s, 1, nil, 1, 0)
  S.setPrice(item, { vendor = 5, ah = 100, de = "x" })
  h.eq(item.price, { vendor = 5, ah = 100 })
  S.setPrice(item, { ah = 95, ahGross = 100 }) -- after the 5% cut
  h.eq(item.price, { ah = 95, cut = true })
  S.stop(s, 3)
  h.eq(S.addCurrency(s, 3008, nil, 1, 4), false)
  S.reset(s, 10)
  h.eq(s.currencies, {})
  h.eq(s.places, {})
end)

