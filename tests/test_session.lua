  S.start(s, 600)
  h.eq(S.elapsed(s, 660), 160)
  S.start(s, 640)
  h.eq(S.elapsed(s, 660), 160)
  h.eq(S.add(s, 5, L, 1, 700), true)
end)

h.test("Session.reset keeps run state", function()
  local s = S.new(0)
  S.add(s, 5, L, 3, 10)
  S.reset(s, 50)
  h.eq(count(s.items), 0)
  h.eq(s.running, true)
