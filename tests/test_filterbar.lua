local h = ...
local ns = h.load({ "Theme.lua", "View.lua", "UI/FilterBar.lua" })
local F = ns.UI.FilterBar

h.test("parseMinGold", function()
  h.eq(F.parseMinGold(""), 0)
  h.eq(F.parseMinGold("   "), 0)
  h.eq(F.parseMinGold(nil), 0)
  h.eq(F.parseMinGold("abc"), 0)
  h.eq(F.parseMinGold("-5"), 0)
  h.eq(F.parseMinGold("nan"), 0)
  h.eq(F.parseMinGold("inf"), 0)
  h.eq(F.parseMinGold("5"), 50000)
  h.eq(F.parseMinGold(" 2.5 "), 25000)
  h.eq(F.parseMinGold("0"), 0)
  h.eq(F.parseMinGold("99999999999"), 10000000 * 10000)
end)

h.test("formatMinGold", function()
  h.eq(F.formatMinGold(0), "")
  h.eq(F.formatMinGold(nil), "")
  h.eq(F.formatMinGold(50000), "5")
  h.eq(F.formatMinGold(25000), "2.5")
  h.eq(F.formatMinGold(12345), "1.2345")
  h.eq(F.parseMinGold(F.formatMinGold(12345)), 12345)
end)

h.test("toggleQuality", function()
  local f = {}
  F.toggleQuality(f, 3)
  h.eq(f.qualities[3], false)
  h.eq(f.qualities[0], true)
  h.eq(f.qualities[7], true)
  F.toggleQuality(f, 3)
  h.eq(f.qualities[3], true)
  F.toggleQuality(f, 9)
  F.toggleQuality(f, -1)
  F.toggleQuality(f, 1.5)
  h.eq(f.qualities[9], nil)
  h.eq(f.qualities[-1], nil)
end)

h.test("sorts", function()
  h.eq(#F.SORTS, 4)
  h.eq(F.nextSort("ah"), "vendor")
  h.eq(F.nextSort("recent"), "ah")
  h.eq(F.nextSort("bogus"), "ah")
  h.eq(type(F.sortLabel("name")), "string")
  h.eq(F.sortLabel("bogus"), F.sortLabel("ah"))
end)

h.test("isActive", function()
  h.eq(F.isActive({ filter = { qualities = nil, minValue = 0, search = "" } }), false)
  h.eq(F.isActive({ filter = { minValue = 1, search = "" } }), true)
  h.eq(F.isActive({}), false)
end)

h.test("repair fixes wrong-typed saved state in place", function()
  local db = { filter = "x", sort = 5 }
  F.repair(db)
  h.eq(type(db.filter), "table")
  h.eq(db.filter.qualities[0], true)
  h.eq(db.filter.qualities[7], true)
  h.eq(db.filter.minValue, 0)
  h.eq(db.filter.search, "")
  h.eq(db.sort, "ah")
  local f = { qualities = { [2] = false }, minValue = 5, search = "a" }
  local db2 = { filter = f, sort = "name" }
  F.repair(db2)
  h.eq(db2.filter, f)
  h.eq(f.qualities[2], false)
  h.eq(db2.sort, "name")
  h.eq(F.repair(nil), nil)
end)
